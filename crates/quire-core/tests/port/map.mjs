// Builds tests/VSCODE-MAP.md and applies triage statuses to fixtures.
// Usage: node map.mjs <fixtures dir> <results.tsv> <triage.json> <out VSCODE-MAP.md> <vscode sha>
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const [dir, tsvPath, triagePath, outPath, sha] = process.argv.slice(2);
const results = new Map();
for (const line of readFileSync(tsvPath, 'utf8').split('\n')) {
  if (!line) continue;
  const [file, name, status, err] = line.split('\t');
  results.set(`${file} :: ${name}`, { status, err });
}
const triage = JSON.parse(readFileSync(triagePath, 'utf8'));
const esc = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
let md = `# VS Code test map\n\nEvery test of the VS Code suites ported so far (microsoft/vscode @ \`${sha}\`), with the quire fixture that\ntranslates it or why it is not applicable. Generated by \`tests/port/map.mjs\` from the fixtures, the\nharness results and \`tests/port/triage.json\`. Status: \`pass\`; \`fail (ours: …)\` = a deliberate difference or a\nmissing quire feature; \`fail (bug: …)\` = a quire bug to fix.\n\n`;
const totals = { tests: 0, translated: 0, pass: 0, ours: 0, bug: 0, na: 0 };
for (const f of readdirSync(dir).filter((f) => f.endsWith('.summary.json')).sort()) {
  const fixture = f.replace('.summary.json', '.fixture');
  const summary = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  md += `## ${fixture.replace('.fixture', '.ts')}\n\n| VS Code test | quire | status |\n|---|---|---|\n`;
  let fx = readFileSync(join(dir, fixture), 'utf8');
  for (const t of summary) {
    totals.tests++;
    if (t.na) {
      totals.na++;
      md += `| ${esc(t.name)} | N/A: ${esc(t.na)} | — |\n`;
      continue;
    }
    totals.translated++;
    const flat = t.name.replace(/\n/g, ' ');
    const r = results.get(`${fixture} :: ${flat.trim()}`);
    let status;
    if (!r) status = 'not run';
    else if (r.status === 'pass') { status = 'pass'; totals.pass++; }
    else {
      const tri = triage[t.name];
      const why = tri || (t.features && t.features.length ? `ours: needs ${t.features.join(', ')}` : `bug: ${r.err}`);
      status = `fail (${why})`;
      if (why.startsWith('bug')) totals.bug++; else totals.ours++;
      const header = `=== ${flat}\n`;
      const i = fx.indexOf(header);
      if (i >= 0 && !fx.slice(i + header.length).startsWith('status:')) {
        const kind = why.startsWith('bug') ? 'fail-bug' : 'fail-ours';
        fx = fx.slice(0, i + header.length) + `status: ${kind} ${why.replace(/^(ours|bug): /, '')}\n` + fx.slice(i + header.length);
      }
    }
    md += `| ${esc(t.name)} | \`fixtures/monaco/${fixture}\` | ${esc(status)} |\n`;
  }
  writeFileSync(join(dir, fixture), fx);
  md += '\n';
}
md += `## Totals\n\n- VS Code tests listed: ${totals.tests}\n- translated: ${totals.translated} (pass ${totals.pass}, fail ours ${totals.ours}, fail bug ${totals.bug})\n- N/A: ${totals.na}\n`;
writeFileSync(outPath, md);
console.log(totals);
